#!/usr/bin/env bash
# Prints a Markdown report of all commits made on one day (all branches).
# Usage: scripts/daily-report.sh [YYYY-MM-DD]   (default: today in $TZ)
set -eu

day="${1:-$(date +%F)}"
next=$(date -j -v+1d -f %F "$day" +%F 2>/dev/null || date -d "$day +1 day" +%F)

log=$(git log --all --no-merges --reverse \
  --since="$day 00:00" --until="$next 00:00" \
  --invert-grep --grep='^docs(report):' \
  --format='### %s%n%n`%h` · %ad · %an%n%n%b%n' --date=format:%H:%M)

count=$(git log --all --no-merges --since="$day 00:00" --until="$next 00:00" \
  --invert-grep --grep='^docs(report):' --format=%h | wc -l | tr -d ' ')

printf '# Отчёт за %s\n\n<!-- generated by scripts/daily-report.sh -->\n\n' "$day"
printf 'Коммитов за день: %s.\n\n' "$count"
[ "$count" -eq 0 ] && exit 0
printf '%s\n' "$log" | grep -v '^Co-Authored-By:' | cat -s
